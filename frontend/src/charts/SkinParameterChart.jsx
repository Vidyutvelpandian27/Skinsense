import React from "react";

const SkinParameterChart = ({ parameters = {} }) => {
  const defaultParameters = [
    {
      key: "redness",
      name: "Redness",
      value: 25,
    },
    {
      key: "dark_spots",
      name: "Dark Spots",
      value: 20,
    },
    {
      key: "wrinkles",
      name: "Wrinkles",
      value: 45,
    },
    {
      key: "texture",
      name: "Texture",
      value: 30,
    },
    {
      key: "oiliness",
      name: "Oiliness",
      value: 35,
    },
    {
      key: "dryness",
      name: "Dryness",
      value: 50,
    },
    {
      key: "skin_tone",
      name: "Skin Tone",
      value: 80,
    },
    {
      key: "tone_uniformity",
      name: "Tone Uniformity",
      value: 75,
    },
  ];

  const parameterList = defaultParameters.map((parameter) => {
    const backendValue = parameters[parameter.key];

    if (backendValue === undefined || backendValue === null) {
      return parameter;
    }

    return {
      ...parameter,
      value:
        typeof backendValue === "object"
          ? backendValue.value ?? parameter.value
          : backendValue,
    };
  });

  return (
    <div className="card border-0 shadow-sm">

      <div className="card-body p-4">

        {/* Header */}
        <div className="mb-4">
          <h5 className="fw-bold mb-1">
            Skin Parameter Analysis
          </h5>

          <p className="text-muted mb-0">
            Visual comparison of the detected skin parameters.
          </p>
        </div>

        {/* Chart */}
        <div className="w-100">

          {parameterList.map((parameter) => {
            const value = Math.min(
              100,
              Math.max(0, Number(parameter.value) || 0)
            );

            return (
              <div
                key={parameter.key}
                className="mb-4"
              >

                {/* Label */}
                <div className="d-flex justify-content-between mb-2">

                  <span className="fw-semibold">
                    {parameter.name}
                  </span>

                  <span className="text-muted">
                    {value}%
                  </span>

                </div>

                {/* Progress Bar */}
                <div
                  className="progress"
                  style={{
                    height: "12px",
                    borderRadius: "10px",
                  }}
                >

                  <div
                    className="progress-bar bg-success"
                    role="progressbar"
                    style={{
                      width: `${value}%`,
                      borderRadius: "10px",
                    }}
                    aria-valuenow={value}
                    aria-valuemin="0"
                    aria-valuemax="100"
                  ></div>

                </div>

              </div>
            );
          })}

        </div>

        {/* Explanation */}
        <div className="alert alert-light border mt-4 mb-0">

          <small className="text-muted">
            <strong>Note:</strong>{" "}
            The displayed values represent image-based measurements
            generated by the SkinSense analysis system. They are
            intended for preliminary assessment and should not be
            considered a medical diagnosis.
          </small>

        </div>

      </div>

    </div>
  );
};

export default SkinParameterChart;